#!/bin/bash
set -euo pipefail

mariadb --protocol=socket -uroot -p"${MARIADB_ROOT_PASSWORD}" <<SQL
CREATE USER IF NOT EXISTS '${GALERA_SST_USER}'@'%' IDENTIFIED BY '${GALERA_SST_PASSWORD}';
GRANT RELOAD, PROCESS, LOCK TABLES, REPLICATION CLIENT, BINLOG MONITOR ON *.* TO '${GALERA_SST_USER}'@'%';

CREATE USER IF NOT EXISTS '${GALERA_HC_USER}'@'%' IDENTIFIED BY '${GALERA_HC_PASSWORD}';
GRANT USAGE ON *.* TO '${GALERA_HC_USER}'@'%';

FLUSH PRIVILEGES;
SQL
